/**
 * Bundles the shipped skills (src/lib/infrastructure/assistant/skills/<name>/SKILL.md) into
 * src/lib/infrastructure/assistant/skills/shipped-skills.generated.ts so the browser needs no filesystem.
 *
 *   npm run assistant:build-skills
 *
 * test/sdk/assistant/shipped-skills.test.ts fails when the generated module is out of date.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseSkillMarkdown } from '../../src/lib/infrastructure/assistant/skills/skill-md.ts';
import type { SkillDefinition } from '../../src/lib/core/entity/assistant/skill.ts';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, '..', '..');
const skillsDir = join(repoRoot, 'src/lib/infrastructure/assistant/skills');
const outFile = join(skillsDir, 'shipped-skills.generated.ts');

function main(): void {
    const skills: SkillDefinition[] = [];
    const failures: string[] = [];
    for (const entry of readdirSync(skillsDir).sort()) {
        const dir = join(skillsDir, entry);
        if (!statSync(dir).isDirectory()) continue;
        const result = parseSkillMarkdown(readFileSync(join(dir, 'SKILL.md'), 'utf8'), { source: 'shipped', dirName: entry });
        if (!result.ok) failures.push(`${entry}: ${result.errors.join('; ')}`);
        else skills.push(result.skill);
    }
    if (failures.length > 0) throw new Error(`Invalid shipped skills:\n${failures.join('\n')}`);

    const source = [
        '// Generated by tools/assistant/build-shipped-skills.ts from the SKILL.md files in this folder.',
        '// Do not edit by hand: change a SKILL.md and run `npm run assistant:build-skills`.',
        "import type { SkillDefinition } from '@/lib/core/entity/assistant/skill';",
        '',
        `export const SHIPPED_SKILLS: SkillDefinition[] = ${JSON.stringify(skills, null, 4)};`,
        '',
    ].join('\n');
    writeFileSync(outFile, source);
    // Format with the repo's Prettier so `npm run prettier:check` passes on the generated file.
    execFileSync(process.execPath, [join(repoRoot, 'node_modules/prettier/bin-prettier.js'), '--write', outFile], { stdio: 'inherit' });
    console.log(`Wrote ${skills.length} shipped skills to src/lib/infrastructure/assistant/skills/shipped-skills.generated.ts`);
}

try {
    main();
} catch (error: unknown) {
    console.error(error instanceof Error ? error.message : error);
    process.exit(1);
}
